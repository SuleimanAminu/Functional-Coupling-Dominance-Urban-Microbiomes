import pandas as pd
import numpy as np
from scipy.stats import spearmanr, entropy

# ---------- LOAD DATA ----------
df = pd.read_csv("Combined_ARG_VFDB_Harmonized.tsv", sep="\t")

# ==========================================================
# COMPUTE SUMMARY METRICS PER SAMPLE
# ==========================================================
summary = df.groupby(["Sample_ID", "Data_source"]).agg(
    Total_TPM=("TPM", "sum"),
    Mechanism_Richness=("Mechanisms", "nunique")
).reset_index()

# Pivot to wide format
summary_wide = summary.pivot(index="Sample_ID", columns="Data_source", values=["Total_TPM", "Mechanism_Richness"]).fillna(0)
summary_wide.columns = ["_".join(col).strip() for col in summary_wide.columns.values]
summary_wide.reset_index(inplace=True)

# ==========================================================
# BALANCE METRICS
# ==========================================================
# ARG–VF TPM ratio (avoid division by zero)
summary_wide["ARG_VF_TPM_ratio"] = np.log2((summary_wide["Total_TPM_ARG"] + 1) / (summary_wide["Total_TPM_VF"] + 1))

# ARG–VF richness ratio
summary_wide["ARG_VF_richness_ratio"] = np.log2((summary_wide["Mechanism_Richness_ARG"] + 1) / (summary_wide["Mechanism_Richness_VF"] + 1))

# ==========================================================
# CORRELATION (global co-selection strength)
# ==========================================================
corr, pval = spearmanr(summary_wide["Total_TPM_ARG"], summary_wide["Total_TPM_VF"])
print(f"\n Global ARG–VF TPM correlation (Spearman): r = {corr:.3f}, p = {pval:.2e}")

# ==========================================================
# ENTROPY-BASED INTEGRATION SCORE
# ==========================================================
# Calculate normalized Shannon entropy for ARG/VF balance per sample
def integration_entropy(row):
    probs = np.array([row["Total_TPM_ARG"], row["Total_TPM_VF"]])
    probs = probs / probs.sum()
    return entropy(probs, base=2)

summary_wide["Integration_Entropy"] = summary_wide.apply(integration_entropy, axis=1)

# ==========================================================
# SAVE SUMMARY TABLE
# ==========================================================
summary_wide.to_csv("ARG_VF_Functional_Integration_Summary.tsv", sep="\t", index=False)

# ==========================================================
# SUMMARY STATS
# ==========================================================
print("\n ARG–VF Functional Integration Summary:")
