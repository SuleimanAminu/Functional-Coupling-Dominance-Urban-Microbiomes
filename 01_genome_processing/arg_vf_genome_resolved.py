def remove_vfc_codes(text):
    """Remove VFDB codes (e.g., 'VFC0271') and extra spaces."""
    if pd.isna(text):
        return text
    text = str(text)
    text = re.sub(r'\bVFC\d+\b', '', text)   # remove codes like VFC0271
    text = re.sub(r'\s+', ' ', text)         # remove multiple spaces
    return text.strip()

