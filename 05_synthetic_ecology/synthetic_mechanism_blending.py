import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
import pandas as pd
import math

# Load synthetic mixing results
df = pd.read_csv("Synthetic_Mechanism_Mixing_Results.csv")

sns.set_theme(style="white")

pairs = df[["Donor", "Recipient"]].drop_duplicates()
n_pairs = len(pairs)

cols = 3
rows = math.ceil(n_pairs / cols)

max_entropy = np.log2(df["Predicted"].nunique())

fig, axes = plt.subplots(rows, cols, figsize=(cols * 5, rows * 4), squeeze=False)

for i, ((donor, recipient), sub) in enumerate(df.groupby(["Donor", "Recipient"])):
    r, c = divmod(i, cols)
    ax = axes[r][c]

    summary = (
        sub
        .groupby("Alpha_donor")["Entropy"]
        .agg(["mean", "std"])
        .reset_index()
    )

    ax.plot(
        summary["Alpha_donor"],
        summary["mean"],
        marker="o",
        linewidth=2
    )

    ax.fill_between(
        summary["Alpha_donor"],
        summary["mean"] - summary["std"],
        summary["mean"] + summary["std"],
        alpha=0.25
    )

    ax.axhline(max_entropy, linestyle="--", color="red", linewidth=1)
    ax.axvline(0.5, linestyle="--", color="grey", linewidth=1)

    ax.set_title(f"{donor} → {recipient}", fontsize=12, weight="bold")
    ax.set_xlabel(f"Fraction of {donor}", fontsize=10)
    ax.set_ylabel("Prediction entropy", fontsize=10)

    ax.set_ylim(0, max_entropy + 0.2)

# Remove empty panels
for j in range(i + 1, rows * cols):
    fig.delaxes(axes[j // cols][j % cols])

plt.tight_layout()
plt.savefig(
    "Mechanism_Synthetic_Mixing_Entropy_Curves.tiff",
    dpi=600,
    bbox_inches="tight"
)
plt.show()
