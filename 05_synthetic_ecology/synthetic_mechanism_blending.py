# ------------------------------------------------------------
# Helper: recompute FID metrics from a mixed mechanism vector
# ------------------------------------------------------------

def recompute_fid(mixed_mech, arg_idx, vf_idx):
    """
    mixed_mech: 1D numpy array of CLR mechanism values (length 23)
    arg_idx, vf_idx: indices of ARG and VF mechanisms
    """

    # Convert CLR → pseudo-abundance
    abund = np.exp(mixed_mech)
    abund = abund / abund.sum()

    # Split ARG / VF
    abund_arg = abund[arg_idx]
    abund_vf  = abund[vf_idx]

    # Shannon entropies
    H_ARG = entropy(abund_arg, base=2) if abund_arg.sum() > 0 else 0
    H_VF  = entropy(abund_vf,  base=2) if abund_vf.sum() > 0 else 0
    H_TOT = entropy(abund, base=2)

    # Evenness
    J_ARG = H_ARG / np.log2(len(abund_arg)) if len(abund_arg) > 1 else 0
    J_VF  = H_VF  / np.log2(len(abund_vf))  if len(abund_vf)  > 1 else 0

    # Coupling
    FCR = np.log2((H_ARG + 1e-6) / (H_VF + 1e-6))
    Integration_Index = (H_TOT - abs(H_ARG - H_VF)) / H_TOT if H_TOT > 0 else 0

    return [H_ARG, H_VF, H_TOT, J_ARG, J_VF, FCR, Integration_Index]


