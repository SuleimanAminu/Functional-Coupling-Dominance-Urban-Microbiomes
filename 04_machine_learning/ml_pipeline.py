import pandas as pd
import numpy as np

from sklearn.ensemble import RandomForestClassifier
from sklearn.inspection import permutation_importance
from sklearn.metrics import matthews_corrcoef, balanced_accuracy_score

# ------------------------------------------------------------
# 1. LOAD FINAL DATA SPLITS
# ------------------------------------------------------------

X_train = pd.read_csv("X_train.csv", index_col=0)
X_hold  = pd.read_csv("X_holdout.csv", index_col=0)

y_train = pd.read_csv("y_train.csv", index_col=0).iloc[:, 0]
y_hold  = pd.read_csv("y_holdout.csv", index_col=0).iloc[:, 0]

print("Training set:", X_train.shape)
print("Holdout set :", X_hold.shape)

# ------------------------------------------------------------
# 2. TRAIN FINAL RANDOM FOREST (BEST PARAMS)
# ------------------------------------------------------------

rf_final = RandomForestClassifier(
    n_estimators=800,
    max_depth=None,
    min_samples_split=5,
    min_samples_leaf=1,
    max_features="sqrt",
    class_weight="balanced",
    random_state=42,
    n_jobs=-1
)

rf_final.fit(X_train, y_train)

# ------------------------------------------------------------
# 3. GINI IMPORTANCE
# ------------------------------------------------------------

gini_imp = pd.DataFrame({
    "Feature": X_train.columns,
    "Gini_importance": rf_final.feature_importances_
}).sort_values(
    "Gini_importance", ascending=False
).reset_index(drop=True)

gini_imp["Gini_rank"] = gini_imp.index + 1

# ------------------------------------------------------------
# 4. PERMUTATION IMPORTANCE (HOLDOUT ONLY)
# ------------------------------------------------------------

perm = permutation_importance(
    rf_final,
    X_hold,
    y_hold,
    scoring="balanced_accuracy",
    n_repeats=50,
    random_state=42,
    n_jobs=-1
)

perm_imp = pd.DataFrame({
    "Feature": X_train.columns,
    "Permutation_mean": perm.importances_mean,
    "Permutation_std": perm.importances_std
}).sort_values(
    "Permutation_mean", ascending=False
).reset_index(drop=True)

perm_imp["Permutation_rank"] = perm_imp.index + 1

# ------------------------------------------------------------
# 5. MERGE + CONSENSUS FEATURES
# ------------------------------------------------------------

importance = (
    gini_imp
    .merge(perm_imp, on="Feature")
)

# Define consensus threshold
TOP_N = 20

importance["Consensus"] = (
    (importance["Gini_rank"] <= TOP_N) &
    (importance["Permutation_rank"] <= TOP_N)
)
# ------------------------------------------------------------
# 6. SAVE OUTPUTS
# ------------------------------------------------------------

importance.to_csv(
    "ML_Feature_Importance_Gini_Permutation.csv",
    index=False
)

consensus = importance[importance["Consensus"]].copy()

consensus.to_csv(
    "ML_Feature_Consensus_TOP20.csv",
    index=False
)

print("\n FEATURE IMPORTANCE COMPLETE")
print("Saved:")
print(" - ML_Feature_Importance_Gini_Permutation.csv")
print(" - ML_Feature_Consensus_TOP20.csv")

print("\nConsensus features:")
print(consensus[[
    "Feature",
    "Gini_rank",
    "Permutation_rank"
]])

