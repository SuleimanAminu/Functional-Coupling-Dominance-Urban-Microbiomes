import pandas as pd
import numpy as np

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import StratifiedKFold, GridSearchCV
from sklearn.metrics import (
    matthews_corrcoef,
    balanced_accuracy_score,
    f1_score,
    classification_report,
    confusion_matrix
)

# ------------------------------------------------------------
# 1. LOAD TRAIN / HOLDOUT DATA (CORRECT FILES)
# ------------------------------------------------------------

X_train = pd.read_csv("X_train.csv", index_col=0)
X_holdout = pd.read_csv("X_holdout.csv", index_col=0)

y_train = pd.read_csv("y_train.csv", index_col=0).iloc[:, 0]
y_holdout = pd.read_csv("y_holdout.csv", index_col=0).iloc[:, 0]

print("Training set:", X_train.shape)
print("Holdout set :", X_holdout.shape)

# ------------------------------------------------------------
# 2. DEFINE MODEL + PARAMETER GRID
# ------------------------------------------------------------

rf = RandomForestClassifier(
    random_state=42,
    n_jobs=-1
)

param_grid = {
    "n_estimators": [300, 500, 800],
    "max_depth": [None, 10, 20],
    "min_samples_split": [2, 5, 10],
    "min_samples_leaf": [1, 2, 5],
    "max_features": ["sqrt", "log2"],
    "class_weight": ["balanced"]
}

# ------------------------------------------------------------
# 3. NESTED CROSS-VALIDATION (TRAINING SET ONLY)
# ------------------------------------------------------------

outer_cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
inner_cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

outer_results = []

print("\n Starting nested cross-validation...")

for fold, (tr_idx, te_idx) in enumerate(outer_cv.split(X_train, y_train), 1):

    X_tr, X_te = X_train.iloc[tr_idx], X_train.iloc[te_idx]
    y_tr, y_te = y_train.iloc[tr_idx], y_train.iloc[te_idx]

    grid = GridSearchCV(
        estimator=rf,
        param_grid=param_grid,
        scoring="balanced_accuracy",
        cv=inner_cv,
        n_jobs=-1,
        refit=True
    )

    grid.fit(X_tr, y_tr)
    best_model = grid.best_estimator_

    y_pred = best_model.predict(X_te)

    outer_results.append({
        "Fold": fold,
        "MCC": matthews_corrcoef(y_te, y_pred),
        "BalancedAccuracy": balanced_accuracy_score(y_te, y_pred),
        "MacroF1": f1_score(y_te, y_pred, average="macro")
    })

    print(f"  Fold {fold} done.")

cv_results = pd.DataFrame(outer_results)

cv_results.to_csv(
    "RF_NestedCV_Training_Performance.csv",
    index=False
)

print("\n=== NESTED CV PERFORMANCE (TRAINING) ===")
print(cv_results.describe())

# ------------------------------------------------------------
# 4. TRAIN FINAL MODEL ON FULL TRAINING SET
# ------------------------------------------------------------

print("\n Training final model on full training set...")

final_grid = GridSearchCV(
    estimator=rf,
    param_grid=param_grid,
    scoring="balanced_accuracy",
    cv=inner_cv,
    n_jobs=-1,
    refit=True
)

final_grid.fit(X_train, y_train)
final_model = final_grid.best_estimator_

print("Best parameters:")
print(final_grid.best_params_)

# ------------------------------------------------------------
# 5. FINAL HOLDOUT EVALUATION (ONCE)
# ------------------------------------------------------------

print("\n Evaluating on holdout set...")

y_holdout_pred = final_model.predict(X_holdout)

holdout_metrics = {
    "MCC": matthews_corrcoef(y_holdout, y_holdout_pred),
    "BalancedAccuracy": balanced_accuracy_score(y_holdout, y_holdout_pred),
    "MacroF1": f1_score(y_holdout, y_holdout_pred, average="macro")
}

holdout_df = pd.DataFrame([holdout_metrics])
holdout_df.to_csv(
    "RF_Final_Holdout_Performance.csv",
    index=False
)

print("\n=== FINAL HOLDOUT PERFORMANCE ===")
print(holdout_df)

# Confusion matrix
cm = confusion_matrix(
    y_holdout,
    y_holdout_pred,
    labels=final_model.classes_
)

cm_df = pd.DataFrame(
    cm,
    index=final_model.classes_,
    columns=final_model.classes_
)

cm_df.to_csv("RF_Holdout_Confusion_Matrix.csv")

print("\nClassification report:")
print(classification_report(y_holdout, y_holdout_pred))

print("\n RandomForest nested CV + holdout evaluation COMPLETE.")

